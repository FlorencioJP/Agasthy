#!/usr/bin/env node
// Regenerate TypeScript bindings from Rust types (ts-rs) and the index file.
// With --check, fail if the committed bindings differ from freshly generated ones.

import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync, existsSync, rmSync, mkdirSync, cpSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "packages/shared-types/src/generated");
const indexFile = join(root, "packages/shared-types/src/index.ts");
const check = process.argv.includes("--check");

function snapshot(dir) {
  const files = {};
  if (!existsSync(dir)) return files;
  const walk = (d, prefix = "") => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p, prefix + e.name + "/");
      else files[prefix + e.name] = readFileSync(p, "utf8");
    }
  };
  walk(dir);
  return files;
}

const before = check ? snapshot(outDir) : null;
const beforeIndex = check && existsSync(indexFile) ? readFileSync(indexFile, "utf8") : null;
const backup = check ? join(tmpdir(), `agasthy-types-${process.pid}`) : null;
if (check && existsSync(outDir)) cpSync(outDir, backup, { recursive: true });

// ts-rs writes bindings when its generated `export_bindings_*` tests run.
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
execFileSync("cargo", ["test", "--workspace", "--quiet", "export_bindings"], {
  cwd: root,
  stdio: ["ignore", "ignore", "inherit"],
});

const modules = readdirSync(outDir)
  .filter((f) => f.endsWith(".ts"))
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();
const index =
  "// Generated by scripts/gen-types.mjs. Do not edit.\n" +
  modules.map((m) => `export type * from "./generated/${m}";`).join("\n") +
  "\n";
writeFileSync(indexFile, index);

if (check) {
  const after = snapshot(outDir);
  const changed = [...new Set([...Object.keys(before), ...Object.keys(after)])].filter(
    (k) => before[k] !== after[k],
  );
  if (beforeIndex !== index) changed.push("index.ts");
  if (backup && existsSync(backup)) rmSync(backup, { recursive: true, force: true });
  if (changed.length) {
    console.error("Generated TypeScript bindings are stale. Run `pnpm gen:types`.\n" + changed.join("\n"));
    process.exit(1);
  }
  console.log("TypeScript bindings are up to date.");
} else {
  console.log(`Generated ${modules.length} type modules.`);
}
